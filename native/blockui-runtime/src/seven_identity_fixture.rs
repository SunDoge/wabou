use super::abi;
fn named(scope: &str, item: u64) -> u64 {
    let mut h = abi::key(scope);
    for byte in item.to_le_bytes() {
        h = (h ^ u64::from(byte)).wrapping_mul(0x100000001b3);
    }
    h
}
