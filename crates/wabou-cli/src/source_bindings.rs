use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use syn::{Attribute, Expr, ImplItem, Item, Lit, Meta, Token, Type, punctuated::Punctuated};

use super::Result;
use super::ts_config;

const HEADER: &str = "// AUTO-GENERATED by `wabou bindings`. DO NOT EDIT.\nexport {};\n";

#[derive(Clone, Debug, Eq, PartialEq)]
struct Argument {
    name: String,
    ty: JsType,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct JsType {
    text: String,
    optional: bool,
}

#[derive(Clone, Debug)]
struct Method {
    name: String,
    arguments: Vec<Argument>,
    response: Option<JsType>,
    kind: MethodKind,
    is_static: bool,
    docs: Vec<String>,
    source: String,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum MethodKind {
    Constructor,
    Getter,
    Setter,
    Method,
}

#[derive(Clone, Debug)]
struct Class {
    js_name: String,
    rust_name: String,
    docs: Vec<String>,
    methods: Vec<Method>,
    source: String,
}

#[derive(Clone, Debug)]
struct TypeField {
    name: String,
    ty: JsType,
    docs: Vec<String>,
}

#[derive(Clone, Debug)]
enum TypeKind {
    Object(Vec<TypeField>),
    StringEnum(Vec<String>),
    Alias(JsType),
}

#[derive(Clone, Debug)]
struct TypeDeclaration {
    js_name: String,
    rust_name: String,
    docs: Vec<String>,
    kind: TypeKind,
    source: String,
}

#[derive(Clone, Debug)]
struct HostModule {
    js_name: String,
    rust_name: String,
    docs: Vec<String>,
    methods: Vec<Method>,
    source: String,
}

#[derive(Default)]
struct Scan {
    classes: BTreeMap<String, Class>,
    types: BTreeMap<String, TypeDeclaration>,
    modules: BTreeMap<String, HostModule>,
    implementations: Vec<(String, Vec<Method>)>,
}

pub(super) struct GeneratedBindings {
    pub(super) output: PathBuf,
    pub(super) contents: String,
    pub(super) classes: usize,
    pub(super) types: usize,
    pub(super) modules: usize,
}

pub(super) fn generate(
    app: &Path,
    config: &ts_config::Bindings,
) -> Result<Option<GeneratedBindings>> {
    let files = source_files(app, &config.sources)?;
    let mut scan = Scan::default();
    for path in files {
        let source = fs::read_to_string(&path)
            .map_err(|error| format!("cannot read binding source {}: {error}", path.display()))?;
        if !source.contains("js_class") && !source.contains("::js") {
            continue;
        }
        let file = syn::parse_file(&source)
            .map_err(|error| format!("cannot parse binding source {}: {error}", path.display()))?;
        collect_items(&file.items, &path, &mut scan)?;
    }
    if scan.classes.is_empty()
        && scan.types.is_empty()
        && scan.modules.is_empty()
        && scan.implementations.is_empty()
    {
        return Ok(None);
    }
    attach_methods(&mut scan)?;
    let contents = render(&scan.types, &scan.classes, &scan.modules)?;
    Ok(Some(GeneratedBindings {
        output: app.join(&config.output),
        contents,
        classes: scan.classes.len(),
        types: scan.types.len(),
        modules: scan.modules.len(),
    }))
}

fn source_files(app: &Path, sources: &[PathBuf]) -> Result<Vec<PathBuf>> {
    let mut files = BTreeSet::new();
    for source in sources {
        let source = if source.is_absolute() {
            source.clone()
        } else {
            app.join(source)
        };
        if source.is_file() {
            if source
                .extension()
                .is_some_and(|extension| extension == "rs")
            {
                files.insert(source);
            }
            continue;
        }
        if !source.is_dir() {
            return Err(format!("binding source does not exist: {}", source.display()).into());
        }
        for entry in ignore::WalkBuilder::new(&source)
            .standard_filters(true)
            .build()
        {
            let entry = entry.map_err(|error| {
                format!(
                    "cannot traverse binding source {}: {error}",
                    source.display()
                )
            })?;
            let path = entry.path();
            if entry.file_type().is_some_and(|kind| kind.is_file())
                && path.extension().is_some_and(|extension| extension == "rs")
            {
                files.insert(path.to_path_buf());
            }
        }
    }
    Ok(files.into_iter().collect())
}

fn collect_items(items: &[Item], path: &Path, scan: &mut Scan) -> Result<()> {
    for item in items {
        match item {
            Item::Struct(item)
                if find_wabou_attr(&item.attrs, "js_class").is_some()
                    || find_wabou_attr(&item.attrs, "js_type").is_some() =>
            {
                let class_marker = find_wabou_attr(&item.attrs, "js_class");
                let type_marker = find_wabou_attr(&item.attrs, "js_type");
                if class_marker.is_some() && type_marker.is_some() {
                    return Err(format!(
                        "`{}` cannot be both #[wabou::js_class] and #[wabou::js_type] in {}",
                        item.ident,
                        path.display()
                    )
                    .into());
                }
                if let Some(marker) = type_marker {
                    let declaration = parse_type_marker(
                        marker,
                        &item.ident.to_string(),
                        &item.attrs,
                        item.fields.iter().map(|field| {
                            (
                                field.ident.as_ref().map(ToString::to_string),
                                docs(&field.attrs),
                            )
                        }),
                        path,
                    )?;
                    if !matches!(&declaration.kind, TypeKind::Object(_)) {
                        return Err(format!(
                            "#[wabou::js_type] on struct `{}` must use fields(...) in {}",
                            item.ident,
                            path.display()
                        )
                        .into());
                    }
                    insert_type(scan, declaration, path)?;
                    continue;
                }
                let marker = find_wabou_attr(&item.attrs, "js_class").expect("checked above");
                let rust_name = item.ident.to_string();
                let explicit_name = parse_class_marker(marker)?;
                let qjs_name = parse_rename(&item.attrs)?;
                let class = Class {
                    js_name: explicit_name
                        .or(qjs_name)
                        .unwrap_or_else(|| rust_name.clone()),
                    rust_name: rust_name.clone(),
                    docs: docs(&item.attrs),
                    methods: Vec::new(),
                    source: path.display().to_string(),
                };
                if let Some(previous) = scan.classes.insert(rust_name.clone(), class) {
                    return Err(format!(
                        "duplicate JavaScript class marker for `{rust_name}` in {} and {}",
                        previous.source,
                        path.display()
                    )
                    .into());
                }
            }
            Item::Enum(item) if find_wabou_attr(&item.attrs, "js_type").is_some() => {
                let marker = find_wabou_attr(&item.attrs, "js_type").expect("checked above");
                let declaration = parse_type_marker(
                    marker,
                    &item.ident.to_string(),
                    &item.attrs,
                    std::iter::empty(),
                    path,
                )?;
                if !matches!(&declaration.kind, TypeKind::StringEnum(_)) {
                    return Err(format!(
                        "#[wabou::js_type] on enum `{}` must use values(...) in {}",
                        item.ident,
                        path.display()
                    )
                    .into());
                }
                insert_type(scan, declaration, path)?;
            }
            Item::Type(item) if find_wabou_attr(&item.attrs, "js_type").is_some() => {
                let marker = find_wabou_attr(&item.attrs, "js_type").expect("checked above");
                let declaration = parse_type_marker(
                    marker,
                    &item.ident.to_string(),
                    &item.attrs,
                    std::iter::empty(),
                    path,
                )?;
                if !matches!(&declaration.kind, TypeKind::Alias(_)) {
                    return Err(format!(
                        "#[wabou::js_type] on type alias `{}` must use alias = ... in {}",
                        item.ident,
                        path.display()
                    )
                    .into());
                }
                insert_type(scan, declaration, path)?;
            }
            Item::Mod(item) if find_wabou_attr(&item.attrs, "js_module").is_some() => {
                let marker = find_wabou_attr(&item.attrs, "js_module").expect("checked above");
                let js_name = parse_required_name(marker, "module")?;
                if !has_path(&item.attrs, &["rquickjs", "module"])
                    && !has_path(&item.attrs, &["wabou", "rquickjs", "module"])
                {
                    return Err(format!(
                        "#[wabou::js_module] on `{}` must accompany #[rquickjs::module] in {}",
                        item.ident,
                        path.display()
                    )
                    .into());
                }
                let Some((_, items)) = &item.content else {
                    return Err(format!(
                        "#[wabou::js_module] requires an inline Rust module in {}",
                        path.display()
                    )
                    .into());
                };
                let rust_name = item.ident.to_string();
                let methods = collect_module_functions(&rust_name, items, path)?;
                if methods.is_empty() {
                    return Err(format!(
                        "host module `{js_name}` on `{rust_name}` has no #[rquickjs::function] functions carrying #[wabou::js] in {}",
                        path.display()
                    )
                    .into());
                }
                let module = HostModule {
                    js_name: js_name.clone(),
                    rust_name,
                    docs: docs(&item.attrs),
                    methods,
                    source: path.display().to_string(),
                };
                if let Some(previous) = scan.modules.insert(js_name.clone(), module) {
                    return Err(format!(
                        "duplicate host module `{js_name}` in {} and {}",
                        previous.source,
                        path.display()
                    )
                    .into());
                }
            }
            Item::Impl(item) if has_path(&item.attrs, &["rquickjs", "methods"]) => {
                let Some(rust_name) = impl_type_name(&item.self_ty) else {
                    continue;
                };
                let methods = collect_marked_methods(&rust_name, &item.items, path, true)?;
                if !methods.is_empty() {
                    scan.implementations.push((rust_name, methods));
                }
            }
            Item::Mod(module) => {
                if let Some((_, items)) = &module.content {
                    collect_items(items, path, scan)?;
                }
            }
            _ => {}
        }
    }
    Ok(())
}

fn collect_module_functions(rust_name: &str, items: &[Item], path: &Path) -> Result<Vec<Method>> {
    let mut methods = Vec::new();
    for item in items {
        let Item::Fn(function) = item else {
            continue;
        };
        let Some(marker) = find_wabou_attr(&function.attrs, "js") else {
            continue;
        };
        if !has_path(&function.attrs, &["rquickjs", "function"])
            && !has_path(&function.attrs, &["wabou", "rquickjs", "function"])
        {
            return Err(format!(
                "{rust_name}::{} has #[wabou::js] but no #[rquickjs::function] in {}",
                function.sig.ident,
                path.display()
            )
            .into());
        }
        if qjs_flag(&function.attrs, "skip")? {
            return Err(format!(
                "{rust_name}::{} is both #[qjs(skip)] and #[wabou::js] in {}",
                function.sig.ident,
                path.display()
            )
            .into());
        }
        let contract = parse_method_marker(marker)?;
        let name = parse_rename(&function.attrs)?.unwrap_or_else(|| function.sig.ident.to_string());
        validate_method_contract(rust_name, &name, MethodKind::Method, &contract, path)?;
        methods.push(Method {
            name,
            arguments: contract.arguments,
            response: contract.response,
            kind: MethodKind::Method,
            is_static: false,
            docs: docs(&function.attrs),
            source: path.display().to_string(),
        });
    }
    Ok(methods)
}

fn collect_marked_methods(
    rust_name: &str,
    members: &[ImplItem],
    path: &Path,
    qjs_kinds: bool,
) -> Result<Vec<Method>> {
    let mut methods = Vec::new();
    for member in members {
        let ImplItem::Fn(method) = member else {
            continue;
        };
        let Some(marker) = find_wabou_attr(&method.attrs, "js") else {
            continue;
        };
        if qjs_flag(&method.attrs, "skip")? {
            return Err(format!(
                "{}::{} is both #[qjs(skip)] and #[wabou::js] in {}",
                rust_name,
                method.sig.ident,
                path.display()
            )
            .into());
        }
        let contract = parse_method_marker(marker)?;
        let kind = if qjs_kinds && qjs_flag(&method.attrs, "constructor")? {
            MethodKind::Constructor
        } else if qjs_kinds && qjs_flag(&method.attrs, "get")? {
            MethodKind::Getter
        } else if qjs_kinds && qjs_flag(&method.attrs, "set")? {
            MethodKind::Setter
        } else {
            MethodKind::Method
        };
        let name = parse_rename(&method.attrs)?.unwrap_or_else(|| method.sig.ident.to_string());
        validate_method_contract(rust_name, &name, kind, &contract, path)?;
        methods.push(Method {
            name,
            arguments: contract.arguments,
            response: contract.response,
            kind,
            is_static: qjs_kinds && qjs_flag(&method.attrs, "static")?,
            docs: docs(&method.attrs),
            source: path.display().to_string(),
        });
    }
    Ok(methods)
}

fn insert_type(scan: &mut Scan, declaration: TypeDeclaration, path: &Path) -> Result<()> {
    let rust_name = declaration.rust_name.clone();
    if let Some(previous) = scan.types.insert(rust_name.clone(), declaration) {
        return Err(format!(
            "duplicate JavaScript type marker for `{rust_name}` in {} and {}",
            previous.source,
            path.display()
        )
        .into());
    }
    Ok(())
}

fn attach_methods(scan: &mut Scan) -> Result<()> {
    for (rust_name, methods) in scan.implementations.drain(..) {
        let Some(class) = scan.classes.get_mut(&rust_name) else {
            return Err(format!(
                "#[wabou::js] methods target `{rust_name}`, but that type has no #[wabou::js_class]"
            )
            .into());
        };
        class.methods.extend(methods);
    }
    Ok(())
}

#[derive(Default)]
struct MethodContract {
    arguments: Vec<Argument>,
    response: Option<JsType>,
}

#[derive(Default)]
struct TypeContract {
    name: Option<String>,
    fields: Option<Vec<TypeField>>,
    values: Option<Vec<String>>,
    alias: Option<JsType>,
}

fn parse_type_marker<I>(
    attribute: &Attribute,
    rust_name: &str,
    attributes: &[Attribute],
    rust_fields: I,
    path: &Path,
) -> Result<TypeDeclaration>
where
    I: IntoIterator<Item = (Option<String>, Vec<String>)>,
{
    if matches!(attribute.meta, Meta::Path(_)) {
        return Err(format!(
            "#[wabou::js_type] on `{rust_name}` in {} requires exactly one of fields(...), values(...), or alias = ...",
            path.display()
        )
        .into());
    }
    let rust_field_docs = rust_fields
        .into_iter()
        .filter_map(|(name, docs)| name.map(|name| (name, docs)))
        .collect::<BTreeMap<_, _>>();
    let mut contract = TypeContract::default();
    attribute.parse_nested_meta(|meta| {
        if meta.path.is_ident("name") {
            let name = meta.value()?.parse::<syn::LitStr>()?.value();
            validate_identifier(&name, "type").map_err(|error| meta.error(error.to_string()))?;
            contract.name = Some(name);
            return Ok(());
        }
        if meta.path.is_ident("fields") {
            if contract.fields.is_some() {
                return Err(meta.error("duplicate fields(...) declaration"));
            }
            let mut fields = Vec::new();
            meta.parse_nested_meta(|field| {
                let Some(identifier) = field.path.get_ident() else {
                    return Err(field.error("field name must be an identifier"));
                };
                let name = identifier.to_string();
                validate_identifier(&name, "field")
                    .map_err(|error| field.error(error.to_string()))?;
                let expression = field.value()?.parse::<Expr>()?;
                let ty = parse_js_type(&expression, true)
                    .map_err(|error| field.error(error.to_string()))?;
                if fields.iter().any(|entry: &TypeField| entry.name == name) {
                    return Err(field.error("duplicate JavaScript field"));
                }
                fields.push(TypeField {
                    docs: rust_field_docs.get(&name).cloned().unwrap_or_default(),
                    name,
                    ty,
                });
                Ok(())
            })?;
            contract.fields = Some(fields);
            return Ok(());
        }
        if meta.path.is_ident("values") {
            if contract.values.is_some() {
                return Err(meta.error("duplicate values(...) declaration"));
            }
            let mut values = Vec::new();
            meta.parse_nested_meta(|value| {
                let Some(identifier) = value.path.get_ident() else {
                    return Err(value.error("enum value name must be an identifier"));
                };
                let value = if value.input.peek(Token![=]) {
                    value.value()?.parse::<syn::LitStr>()?.value()
                } else {
                    identifier.to_string()
                };
                if values.contains(&value) {
                    return Err(meta.error("duplicate JavaScript enum value"));
                }
                values.push(value);
                Ok(())
            })?;
            contract.values = Some(values);
            return Ok(());
        }
        if meta.path.is_ident("alias") {
            let expression = meta.value()?.parse::<Expr>()?;
            contract.alias = Some(
                parse_js_type(&expression, false).map_err(|error| meta.error(error.to_string()))?,
            );
            return Ok(());
        }
        Err(meta.error("supported type options: name, fields(...), values(...), alias"))
    })?;
    let shape_count = usize::from(contract.fields.is_some())
        + usize::from(contract.values.is_some())
        + usize::from(contract.alias.is_some());
    if shape_count != 1 {
        return Err(format!(
            "#[wabou::js_type] on `{rust_name}` in {} requires exactly one of fields(...), values(...), or alias = ...",
            path.display()
        )
        .into());
    }
    let kind = if let Some(fields) = contract.fields {
        TypeKind::Object(fields)
    } else if let Some(values) = contract.values {
        if values.is_empty() {
            return Err(
                format!("JavaScript enum `{rust_name}` must declare at least one value").into(),
            );
        }
        TypeKind::StringEnum(values)
    } else {
        TypeKind::Alias(contract.alias.expect("shape checked"))
    };
    Ok(TypeDeclaration {
        js_name: contract.name.unwrap_or_else(|| rust_name.to_owned()),
        rust_name: rust_name.to_owned(),
        docs: docs(attributes),
        kind,
        source: path.display().to_string(),
    })
}

fn parse_class_marker(attribute: &Attribute) -> Result<Option<String>> {
    if matches!(attribute.meta, Meta::Path(_)) {
        return Ok(None);
    }
    let mut name = None;
    attribute.parse_nested_meta(|meta| {
        if meta.path.is_ident("name") {
            name = Some(meta.value()?.parse::<syn::LitStr>()?.value());
            return Ok(());
        }
        Err(meta.error("supported class option: name = \"JavaScriptName\""))
    })?;
    if let Some(name) = &name {
        validate_identifier(name, "class")?;
    }
    Ok(name)
}

fn parse_required_name(attribute: &Attribute, kind: &str) -> Result<String> {
    let Some(name) = parse_class_marker(attribute)? else {
        return Err(format!("#[wabou::js_{kind}] requires name = \"...\"").into());
    };
    Ok(name)
}

fn parse_method_marker(attribute: &Attribute) -> Result<MethodContract> {
    let mut contract = MethodContract::default();
    attribute.parse_nested_meta(|meta| {
        if meta.path.is_ident("returns") {
            let expression = meta.value()?.parse::<Expr>()?;
            contract.response = Some(
                parse_js_type(&expression, false).map_err(|error| meta.error(error.to_string()))?,
            );
            return Ok(());
        }
        if meta.path.is_ident("args") {
            meta.parse_nested_meta(|argument| {
                let Some(identifier) = argument.path.get_ident() else {
                    return Err(argument.error("argument name must be an identifier"));
                };
                let name = identifier.to_string();
                validate_identifier(&name, "argument")
                    .map_err(|error| argument.error(error.to_string()))?;
                let expression = argument.value()?.parse::<Expr>()?;
                let ty = parse_js_type(&expression, true)
                    .map_err(|error| argument.error(error.to_string()))?;
                if contract
                    .arguments
                    .iter()
                    .any(|argument| argument.name == name)
                {
                    return Err(argument.error("duplicate JavaScript argument"));
                }
                contract.arguments.push(Argument { name, ty });
                Ok(())
            })?;
            return Ok(());
        }
        Err(meta.error(
            "supported method options: args(...), returns; use #[qjs(rename = \"...\")] for the JavaScript name",
        ))
    })?;
    Ok(contract)
}

fn parse_js_type(expression: &Expr, allow_optional: bool) -> Result<JsType> {
    let plain = |text: &str| JsType {
        text: text.to_owned(),
        optional: false,
    };
    if let Expr::Path(path) = expression {
        let Some(identifier) = path.path.get_ident() else {
            return Err("JavaScript primitive must be one identifier".into());
        };
        return Ok(match identifier.to_string().as_str() {
            "string" => plain("string"),
            "boolean" => plain("boolean"),
            "number" | "safe_integer" => plain("number"),
            "bigint" => plain("bigint"),
            "unknown" => plain("unknown"),
            "void" => plain("void"),
            "object" => plain("Record<string, unknown>"),
            "uint8_array" => plain("Uint8Array"),
            "array_buffer" => plain("ArrayBuffer"),
            "undefined" => plain("undefined"),
            other => return Err(format!("unsupported JavaScript type `{other}`").into()),
        });
    }
    let Expr::Call(call) = expression else {
        return Err("JavaScript type must be a supported type name or constructor".into());
    };
    let Expr::Path(function) = call.func.as_ref() else {
        return Err("JavaScript type constructor must be an identifier".into());
    };
    let Some(function) = function.path.get_ident().map(ToString::to_string) else {
        return Err("JavaScript type constructor must be an identifier".into());
    };
    if function == "union" {
        if call.args.len() < 2 {
            return Err("union(...) requires at least two types".into());
        }
        let mut values = Vec::new();
        for argument in &call.args {
            let ty = parse_js_type(argument, false)?;
            values.push(ty.text);
        }
        return Ok(plain(&values.join(" | ")));
    }
    if function == "named" || function == "json" || function == "handle" {
        let name = one_named_argument(&function, &call.args)?;
        return Ok(if function == "handle" {
            plain(&format!("WabouHandle<\"{name}\">"))
        } else {
            plain(&name)
        });
    }
    if function == "literal" {
        let Some(Expr::Lit(value)) = call.args.first() else {
            return Err("literal(...) requires one string, boolean, or number".into());
        };
        if call.args.len() != 1 {
            return Err("literal(...) requires exactly one value".into());
        }
        let text = match &value.lit {
            Lit::Str(value) => serde_json::to_string(&value.value())?,
            Lit::Bool(value) => value.value.to_string(),
            Lit::Int(value) => value.base10_digits().to_owned(),
            Lit::Float(value) => value.base10_digits().to_owned(),
            _ => return Err("unsupported literal type".into()),
        };
        return Ok(plain(&text));
    }
    if call.args.len() != 1 {
        return Err(format!("{function}(...) requires exactly one type").into());
    }
    let inner = parse_js_type(call.args.first().expect("length checked"), false)?;
    Ok(match function.as_str() {
        "array" => plain(&format!("Array<{}>", inner.text)),
        "readonly_array" => plain(&format!("ReadonlyArray<{}>", inner.text)),
        "promise" => plain(&format!("Promise<{}>", inner.text)),
        "nullable" => plain(&format!("{} | null", inner.text)),
        "record" => plain(&format!("Record<string, {}>", inner.text)),
        "optional" if allow_optional => JsType {
            text: inner.text,
            optional: true,
        },
        "optional" => {
            return Err("optional(...) is only valid for arguments or object fields".into());
        }
        _ => return Err(format!("unsupported JavaScript type constructor `{function}`").into()),
    })
}

fn one_named_argument(function: &str, arguments: &Punctuated<Expr, Token![,]>) -> Result<String> {
    if arguments.len() != 1 {
        return Err(format!("{function}(...) requires exactly one type name").into());
    }
    let argument = arguments.first().expect("length checked");
    let name = match argument {
        Expr::Path(path) if path.qself.is_none() => path
            .path
            .segments
            .iter()
            .map(|segment| segment.ident.to_string())
            .collect::<Vec<_>>()
            .join("."),
        Expr::Lit(value) => match &value.lit {
            Lit::Str(value) => value.value(),
            _ => return Err(format!("{function}(...) requires a type name").into()),
        },
        _ => return Err(format!("{function}(...) requires a type name").into()),
    };
    for part in name.split('.') {
        validate_identifier(part, "type")?;
    }
    Ok(name)
}

fn validate_method_contract(
    class: &str,
    method: &str,
    kind: MethodKind,
    contract: &MethodContract,
    path: &Path,
) -> Result<()> {
    if contract
        .arguments
        .windows(2)
        .any(|arguments| arguments[0].ty.optional && !arguments[1].ty.optional)
    {
        return Err(format!(
            "required argument follows an optional argument in {class}::{method} in {}",
            path.display()
        )
        .into());
    }
    match kind {
        MethodKind::Constructor if contract.response.is_some() => Err(format!(
            "constructor {class}::{method} must not declare returns in {}",
            path.display()
        )
        .into()),
        MethodKind::Getter if !contract.arguments.is_empty() || contract.response.is_none() => {
            Err(format!(
                "getter {class}::{method} requires returns and no args in {}",
                path.display()
            )
            .into())
        }
        MethodKind::Setter if contract.arguments.len() != 1 || contract.response.is_some() => {
            Err(format!(
                "setter {class}::{method} requires one arg and no returns in {}",
                path.display()
            )
            .into())
        }
        MethodKind::Method if contract.response.is_none() => Err(format!(
            "method {class}::{method} must declare returns in {}",
            path.display()
        )
        .into()),
        _ => Ok(()),
    }
}

fn render(
    types: &BTreeMap<String, TypeDeclaration>,
    classes: &BTreeMap<String, Class>,
    modules: &BTreeMap<String, HostModule>,
) -> Result<String> {
    let mut output = String::from(HEADER);
    output.push_str(
        "export type WabouHandle<Name extends string> = { readonly lo: number; readonly hi: number } & { readonly __wabouHandle?: Name };\n\n",
    );
    let mut js_names = BTreeSet::from(["WabouHandle".to_owned()]);
    let mut types = types.values().collect::<Vec<_>>();
    types.sort_by(|left, right| left.js_name.cmp(&right.js_name));
    for declaration in types {
        validate_identifier(&declaration.js_name, "type")?;
        if !js_names.insert(declaration.js_name.clone()) {
            return Err(format!(
                "duplicate generated JavaScript name `{}`",
                declaration.js_name
            )
            .into());
        }
        render_type(&mut output, declaration);
    }
    let mut classes = classes.values().collect::<Vec<_>>();
    classes.sort_by(|left, right| left.js_name.cmp(&right.js_name));
    for class in classes {
        validate_identifier(&class.js_name, "class")?;
        if !js_names.insert(class.js_name.clone()) {
            return Err(format!("duplicate generated JavaScript name `{}`", class.js_name).into());
        }
        push_docs(&mut output, &class.docs, "");
        output.push_str(&format!("export declare class {} {{\n", class.js_name));
        render_members(&mut output, class)?;
        output.push_str("}\n\n");
    }
    if !modules.is_empty() {
        output.push_str("declare module \"@wabou/core\" {\n");
        output.push_str("  interface HostModules {\n");
        for module in modules.values() {
            validate_identifier(&module.js_name, "host module")?;
            push_docs(&mut output, &module.docs, "    ");
            output.push_str(&format!("    readonly {}: {{\n", module.js_name));
            render_module_methods(&mut output, module)?;
            output.push_str("    };\n");
        }
        output.push_str("  }\n");
        output.push_str("}\n\n");
    }
    output.truncate(output.trim_end().len());
    output.push('\n');
    Ok(output)
}

fn render_module_methods(output: &mut String, module: &HostModule) -> Result<()> {
    let mut names = BTreeSet::new();
    let mut methods = module.methods.iter().collect::<Vec<_>>();
    methods.sort_by(|left, right| (&left.name, &left.source).cmp(&(&right.name, &right.source)));
    for method in methods {
        if !names.insert(&method.name) {
            return Err(format!(
                "duplicate host function `{}.{}` on `{}`",
                module.js_name, method.name, module.rust_name
            )
            .into());
        }
        push_docs(output, &method.docs, "      ");
        output.push_str(&format!(
            "      {}({}): {};\n",
            method.name,
            render_arguments(&method.arguments),
            method.response.as_ref().expect("validated method").text
        ));
    }
    Ok(())
}

fn render_type(output: &mut String, declaration: &TypeDeclaration) {
    push_docs(output, &declaration.docs, "");
    match &declaration.kind {
        TypeKind::Object(fields) => {
            output.push_str(&format!("export interface {} {{\n", declaration.js_name));
            for field in fields {
                push_docs(output, &field.docs, "  ");
                let optional = if field.ty.optional { "?" } else { "" };
                output.push_str(&format!("  {}{optional}: {};\n", field.name, field.ty.text));
            }
            output.push_str("}\n\n");
        }
        TypeKind::StringEnum(values) => {
            let values = values
                .iter()
                .map(|value| serde_json::to_string(value).expect("strings serialize"))
                .collect::<Vec<_>>()
                .join(" | ");
            output.push_str(&format!(
                "export type {} = {values};\n\n",
                declaration.js_name
            ));
        }
        TypeKind::Alias(alias) => {
            output.push_str(&format!(
                "export type {} = {};\n\n",
                declaration.js_name, alias.text
            ));
        }
    }
}

fn render_members(output: &mut String, class: &Class) -> Result<()> {
    let constructors = class
        .methods
        .iter()
        .filter(|method| method.kind == MethodKind::Constructor)
        .collect::<Vec<_>>();
    if constructors.len() > 1 {
        return Err(format!(
            "class `{}` declares more than one constructor",
            class.rust_name
        )
        .into());
    }
    if let Some(constructor) = constructors.first() {
        push_docs(output, &constructor.docs, "  ");
        output.push_str(&format!(
            "  constructor({});\n",
            render_arguments(&constructor.arguments)
        ));
    }

    let mut properties: BTreeMap<(bool, String), (&Method, Option<&Method>)> = BTreeMap::new();
    for getter in class
        .methods
        .iter()
        .filter(|method| method.kind == MethodKind::Getter)
    {
        let key = (getter.is_static, getter.name.clone());
        if properties.insert(key, (getter, None)).is_some() {
            return Err(format!(
                "duplicate getter `{}` in class `{}`",
                getter.name, class.js_name
            )
            .into());
        }
    }
    for setter in class
        .methods
        .iter()
        .filter(|method| method.kind == MethodKind::Setter)
    {
        let key = (setter.is_static, setter.name.clone());
        let Some(property) = properties.get_mut(&key) else {
            return Err(format!(
                "setter `{}` in class `{}` has no matching getter",
                setter.name, class.js_name
            )
            .into());
        };
        let getter_type = property.0.response.as_ref().expect("validated getter");
        let setter_type = &setter.arguments[0].ty;
        if getter_type.text != setter_type.text {
            return Err(format!(
                "getter/setter type mismatch for `{}.{}`: {} versus {}",
                class.js_name, setter.name, getter_type.text, setter_type.text
            )
            .into());
        }
        property.1 = Some(setter);
    }
    for ((is_static, name), (getter, setter)) in properties {
        push_docs(output, &getter.docs, "  ");
        let static_prefix = if is_static { "static " } else { "" };
        let readonly = if setter.is_none() { "readonly " } else { "" };
        output.push_str(&format!(
            "  {static_prefix}{readonly}{name}: {};\n",
            getter.response.as_ref().expect("validated getter").text
        ));
    }

    let mut methods = class
        .methods
        .iter()
        .filter(|method| method.kind == MethodKind::Method)
        .collect::<Vec<_>>();
    methods.sort_by(|left, right| {
        (left.is_static, &left.name, &left.source).cmp(&(
            right.is_static,
            &right.name,
            &right.source,
        ))
    });
    for method in methods {
        push_docs(output, &method.docs, "  ");
        let static_prefix = if method.is_static { "static " } else { "" };
        output.push_str(&format!(
            "  {static_prefix}{}({}): {};\n",
            method.name,
            render_arguments(&method.arguments),
            method.response.as_ref().expect("validated method").text
        ));
    }
    Ok(())
}

fn render_arguments(arguments: &[Argument]) -> String {
    arguments
        .iter()
        .map(|argument| {
            let optional = if argument.ty.optional { "?" } else { "" };
            format!("{}{optional}: {}", argument.name, argument.ty.text)
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn push_docs(output: &mut String, docs: &[String], indent: &str) {
    if docs.is_empty() {
        return;
    }
    output.push_str(indent);
    output.push_str("/**\n");
    for line in docs {
        output.push_str(indent);
        output.push_str(" *");
        if !line.is_empty() {
            output.push(' ');
            output.push_str(&line.replace("*/", "* /"));
        }
        output.push('\n');
    }
    output.push_str(indent);
    output.push_str(" */\n");
}

fn docs(attributes: &[Attribute]) -> Vec<String> {
    attributes
        .iter()
        .filter(|attribute| attribute.path().is_ident("doc"))
        .filter_map(|attribute| match &attribute.meta {
            Meta::NameValue(value) => match &value.value {
                Expr::Lit(value) => match &value.lit {
                    Lit::Str(value) => Some(value.value().trim().to_owned()),
                    _ => None,
                },
                _ => None,
            },
            _ => None,
        })
        .collect()
}

fn find_wabou_attr<'a>(attributes: &'a [Attribute], name: &str) -> Option<&'a Attribute> {
    attributes.iter().find(|attribute| {
        let parts = attribute
            .path()
            .segments
            .iter()
            .map(|segment| segment.ident.to_string())
            .collect::<Vec<_>>();
        matches!(parts.as_slice(), [prefix, attribute_name]
            if (prefix == "wabou" || prefix == "wabou_bindgen") && attribute_name == name)
    })
}

fn has_path(attributes: &[Attribute], path: &[&str]) -> bool {
    attributes.iter().any(|attribute| {
        attribute
            .path()
            .segments
            .iter()
            .map(|segment| segment.ident.to_string())
            .eq(path.iter().map(|segment| (*segment).to_owned()))
    })
}

fn parse_rename(attributes: &[Attribute]) -> Result<Option<String>> {
    let mut name = None;
    for attribute in attributes.iter().filter(|attribute| {
        attribute.path().is_ident("qjs")
            || has_path(std::slice::from_ref(attribute), &["rquickjs", "class"])
    }) {
        if matches!(attribute.meta, Meta::Path(_)) {
            continue;
        }
        attribute.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename") {
                if meta.input.peek(Token![=]) {
                    let expression = meta.value()?.parse::<Expr>()?;
                    if let Expr::Lit(value) = expression
                        && let Lit::Str(value) = value.lit
                    {
                        name = Some(value.value());
                    }
                }
                return Ok(());
            }
            consume_unknown_meta(meta)
        })?;
    }
    Ok(name)
}

fn qjs_flag(attributes: &[Attribute], flag: &str) -> Result<bool> {
    let mut found = false;
    for attribute in attributes
        .iter()
        .filter(|attribute| attribute.path().is_ident("qjs"))
    {
        attribute.parse_nested_meta(|meta| {
            if meta.path.is_ident(flag) {
                found = if meta.input.peek(Token![=]) {
                    let expression = meta.value()?.parse::<Expr>()?;
                    !matches!(&expression, Expr::Lit(value) if matches!(&value.lit, Lit::Bool(value) if !value.value))
                } else {
                    true
                };
                return Ok(());
            }
            consume_unknown_meta(meta)
        })?;
    }
    Ok(found)
}

fn consume_unknown_meta(meta: syn::meta::ParseNestedMeta<'_>) -> syn::Result<()> {
    if meta.input.peek(Token![=]) {
        let _ = meta.value()?.parse::<Expr>()?;
    } else if meta.input.peek(syn::token::Paren) {
        meta.parse_nested_meta(consume_unknown_meta)?;
    }
    Ok(())
}

fn impl_type_name(ty: &Type) -> Option<String> {
    let Type::Path(path) = ty else {
        return None;
    };
    path.path
        .segments
        .last()
        .map(|segment| segment.ident.to_string())
}

fn validate_identifier(value: &str, kind: &str) -> Result<()> {
    let mut characters = value.chars();
    if !characters.next().is_some_and(|character| {
        character == '_' || character == '$' || character.is_ascii_alphabetic()
    }) || !characters
        .all(|character| character == '_' || character == '$' || character.is_ascii_alphanumeric())
    {
        return Err(format!("invalid JavaScript {kind} identifier `{value}`").into());
    }
    Ok(())
}

