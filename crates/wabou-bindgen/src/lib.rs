//! Deterministic TypeScript declarations and native-widget wrappers.
//!
//! Marker macros annotate Rust-owned QuickJS APIs for source binding generation.
//! The optional `generate` feature provides Specta-backed helpers for legacy flat
//! function modules and typed native-widget wrappers.

#![warn(missing_docs)]

