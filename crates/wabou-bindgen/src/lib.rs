#[cfg(feature = "generate")]
const HEADER: &str = "// AUTO-GENERATED by wabou-bindgen. DO NOT EDIT.\n";

/// One explicitly described function in a flat native interface.
///
/// This contract deliberately does not infer function signatures from Rust
/// types. Native FFI authors write the TypeScript spelling next to the Rust
/// implementation and keep the two semantics aligned.
#[cfg(feature = "generate")]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct NativeMethod {
    name: &'static str,
    arguments: &'static [(&'static str, &'static str)],
    response: &'static str,
    asyncness: bool,
}

#[cfg(feature = "generate")]
impl NativeMethod {
    /// Define a synchronous native method with explicit TypeScript arguments
    /// and response type.
    pub const fn sync(
        name: &'static str,
        arguments: &'static [(&'static str, &'static str)],
        response: &'static str,
    ) -> Self {
        Self {
            name,
            arguments,
            response,
            asyncness: false,
        }
    }

    /// Define an asynchronous native method with explicit TypeScript spelling.
    pub const fn asynchronous(
        name: &'static str,
        arguments: &'static [(&'static str, &'static str)],
        response: &'static str,
    ) -> Self {
        Self {
            name,
            arguments,
            response,
            asyncness: true,
        }
    }
}

/// A generated TypeScript interface for a flat native module that preserves
/// each Rust function's sync/async shape.
#[cfg(feature = "generate")]
pub struct FunctionModule {
    name: String,
    functions: Vec<FunctionSignature>,
    declarations: BTreeMap<String, String>,
}

/// Generated Solid components for Rust-owned native widget configurations.
///
/// Specta supplies the Serde deserialization shape while this module adds the
/// Wabou-specific component name, native tag, reactive configuration wrapper,
/// and presentation-prop split.
#[cfg(feature = "generate")]
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct WidgetModule {
    widgets: Vec<WidgetBinding>,
}

#[cfg(feature = "generate")]
#[derive(Clone, Debug, Eq, PartialEq)]
struct WidgetBinding {
    component: String,
    tag: String,
    config_type: String,
    config_fields: Vec<String>,
    declarations: BTreeMap<String, String>,
}

#[cfg(feature = "generate")]
impl WidgetModule {
    /// Construct an empty native-widget module.
    pub fn new() -> Self {
        Self::default()
    }

    /// Add one component backed by a Serde-deserializable Rust configuration.
    ///
    /// `component` must be a PascalCase TypeScript identifier. `tag` is the
    /// native widget tag registered with the Rust host. Config fields are read
    /// from Specta after applying the Serde deserialization mapping, so renamed,
    /// skipped, and defaulted fields stay aligned with the actual Rust decoder.
    pub fn widget<Config>(mut self, component: impl Into<String>, tag: impl Into<String>) -> Self
    where
        Config: Type + DeserializeOwned,
    {
        let component = component.into();
        let tag = tag.into();
        assert_identifier(&component, "widget component");
        assert!(
            component
                .chars()
                .next()
                .is_some_and(|character| character.is_ascii_uppercase()),
            "widget component `{component}` must start with an uppercase letter"
        );
        assert_native_widget_tag(&tag);
        assert!(
            self.widgets
                .iter()
                .all(|widget| widget.component != component),
            "duplicate widget component `{component}`"
        );
        assert!(
            self.widgets.iter().all(|widget| widget.tag != tag),
            "duplicate native widget tag `{tag}`"
        );

        let mut types = Types::default();
        let config = Config::definition(&mut types);
        let format = specta_serde::PhasesFormat;
        let mapped_types = format
            .map_types(&types)
            .unwrap_or_else(|error| panic!("cannot map widget `{component}` config: {error}"));
        let config = specta_serde::select_phase_datatype(
            &config,
            &mapped_types,
            specta_serde::Phase::Deserialize,
        );
        let config_type = render_mapped_datatype(&mapped_types, &config)
            .unwrap_or_else(|error| panic!("cannot export widget `{component}` config: {error}"));
        let config_fields = named_struct_fields(&mapped_types, &config, &component);
        let declarations = specta_declarations(&types, specta_serde::Phase::Deserialize);
        self.widgets.push(WidgetBinding {
            component,
            tag,
            config_type,
            config_fields,
            declarations,
        });
        self
    }

    /// Render deterministic TSX components and their Rust-derived config types.
    pub fn render(&self) -> String {
        let mut output = String::from(HEADER);
        output.push_str(
            "import { NativeWidget, type PrimitiveProps } from \"@wabou/ui/primitives\";\n",
        );
        output.push_str("import { type JSX, omit } from \"solid-js\";\n\n");

        let mut declarations = BTreeMap::new();
        for widget in &self.widgets {
            merge_declarations(&mut declarations, widget.declarations.clone());
        }
        push_declarations(&mut output, &declarations);

        let mut widgets = self.widgets.iter().collect::<Vec<_>>();
        widgets.sort_by(|left, right| left.component.cmp(&right.component));
        for widget in widgets {
            let props = format!("{}Props", widget.component);
            output.push_str(&format!(
                "export type {props} = Omit<PrimitiveProps, \"children\"> & {};\n\n",
                widget.config_type
            ));
            output.push_str(&format!(
                "/** Typed Solid wrapper for the Rust `{}` native widget. */\n",
                widget.tag
            ));
            output.push_str(&format!(
                "export function {}(props: {props}): JSX.Element {{\n",
                widget.component
            ));
            output.push_str("  const nativeProps = omit(\n    props,");
            for field in &widget.config_fields {
                output.push_str(&format!("\n    \"{field}\","));
            }
            output.push_str("\n  );\n");
            output.push_str(&format!(
                "  const config = (): {} => ({{\n",
                widget.config_type
            ));
            for field in &widget.config_fields {
                output.push_str(&format!("    {field}: props.{field},\n"));
            }
            output.push_str("  });\n\n");
            output.push_str(&format!(
                "  return (\n    <NativeWidget\n      {{...nativeProps}}\n      tag=\"{}\"\n      projectionBoundary\n      config={{config()}}\n    />\n  );\n}}\n\n",
                widget.tag
            ));
        }
        output.truncate(output.trim_end().len());
        output.push('\n');
        output
    }

    /// Render and write the generated TSX module.
    pub fn write(&self, path: impl AsRef<Path>) -> Result<(), BindingsError> {
        write_generated(path.as_ref(), self.render())
    }

    /// Verify that an existing generated TSX module matches the Rust contract.
    pub fn check(&self, path: impl AsRef<Path>) -> Result<(), BindingsError> {
        check_generated(path.as_ref(), self.render())
    }
}

#[cfg(feature = "generate")]
struct FunctionSignature {
    name: String,
    arguments: Vec<(String, String)>,
    response: String,
    asyncness: bool,
}

#[cfg(feature = "generate")]
impl FunctionModule {
    /// Construct an empty flat native module.
    pub fn new(name: impl Into<String>) -> Self {
        let name = name.into();
        assert_identifier(&name, "interface");
        Self {
            name,
            functions: Vec::new(),
            declarations: BTreeMap::new(),
        }
    }

    /// Add an explicitly described native method.
    pub fn method(mut self, method: NativeMethod) -> Self {
        assert_identifier(method.name, "method");
        assert!(
            self.functions
                .iter()
                .all(|current| current.name != method.name),
            "duplicate method `{}` in interface `{}`",
            method.name,
            self.name
        );
        self.functions.push(FunctionSignature {
            name: method.name.to_owned(),
            arguments: method
                .arguments
                .iter()
                .map(|(name, ty)| ((*name).to_owned(), (*ty).to_owned()))
                .collect(),
            response: method.response.to_owned(),
            asyncness: method.asyncness,
        });
        self
    }

    /// Add request DTO declarations from their Serde deserialization shape.
    ///
    /// Native function signatures remain explicit; this only removes the
    /// duplicated hand-written TypeScript declarations for structured values.
    pub fn request_dto<T: Type>(mut self) -> Self {
        let mut types = Types::default();
        T::definition(&mut types);
        merge_declarations(
            &mut self.declarations,
            specta_declarations(&types, specta_serde::Phase::Deserialize),
        );
        self
    }

    /// Add response DTO declarations from their Serde serialization shape.
    pub fn response_dto<T: Type>(mut self) -> Self {
        let mut types = Types::default();
        T::definition(&mut types);
        merge_declarations(
            &mut self.declarations,
            specta_declarations(&types, specta_serde::Phase::Serialize),
        );
        self
    }

    /// Add one hand-written TypeScript declaration used by method signatures.
    pub fn declaration(mut self, name: impl Into<String>, declaration: impl Into<String>) -> Self {
        let name = name.into();
        assert_identifier(&name, "declaration");
        merge_declaration(&mut self.declarations, name, declaration.into());
        self
    }

    /// Render deterministic TypeScript declarations for the native interface.
    pub fn render(&self) -> String {
        let mut output = String::from(HEADER);
        push_declarations(&mut output, &self.declarations);
        output.push_str(&format!("export interface {} {{\n", self.name));
        let mut functions = self.functions.iter().collect::<Vec<_>>();
        functions.sort_by(|left, right| left.name.cmp(&right.name));
        for function in functions {
            let arguments = function
                .arguments
                .iter()
                .map(|(name, ty)| format!("{name}: {ty}"))
                .collect::<Vec<_>>()
                .join(", ");
            let result = &function.response;
            output.push_str(&format!(
                "  {}({arguments}): {};\n",
                function.name,
                if function.asyncness {
                    format!("Promise<{result}>")
                } else {
                    result.to_owned()
                }
            ));
        }
        output.push_str("}\n");
        output
    }

    /// Render and write the generated module, creating parent directories.
    pub fn write(&self, path: impl AsRef<Path>) -> Result<(), BindingsError> {
        write_generated(path.as_ref(), self.render())
    }

    /// Verify that an existing generated module exactly matches current output.
    pub fn check(&self, path: impl AsRef<Path>) -> Result<(), BindingsError> {
        check_generated(path.as_ref(), self.render())
    }
}

#[cfg(feature = "generate")]
fn push_declarations(output: &mut String, declarations: &BTreeMap<String, String>) {
    for declaration in declarations.values() {
        output.push_str("export ");
        output.push_str(declaration.trim());
        output.push_str("\n\n");
    }

    let mut aliases = BTreeMap::new();
    for name in declarations.keys() {
        let Some((base, opposite)) = name
            .strip_suffix("_Serialize")
            .map(|base| (base, format!("{base}_Deserialize")))
            .or_else(|| {
                name.strip_suffix("_Deserialize")
                    .map(|base| (base, format!("{base}_Serialize")))
            })
        else {
            continue;
        };
        if !declarations.contains_key(base) && !declarations.contains_key(&opposite) {
            aliases.insert(base, name);
        }
    }
    for (alias, target) in aliases {
        output.push_str(&format!("export type {alias} = {target};\n\n"));
    }
}

#[cfg(feature = "generate")]
fn merge_declarations(
    target: &mut BTreeMap<String, String>,
    declarations: BTreeMap<String, String>,
) {
    for (name, declaration) in declarations {
        merge_declaration(target, name, declaration);
    }
}

#[cfg(feature = "generate")]
fn merge_declaration(target: &mut BTreeMap<String, String>, name: String, declaration: String) {
    match target.entry(name) {
        std::collections::btree_map::Entry::Vacant(entry) => {
            entry.insert(declaration);
        }
        std::collections::btree_map::Entry::Occupied(entry) => assert_eq!(
            entry.get(),
            &declaration,
            "conflicting TypeScript declaration for `{}`; bridge DTO names must be unique within one generated module",
            entry.key()
        ),
    }
}

#[cfg(feature = "generate")]
fn write_generated(path: &Path, output: String) -> Result<(), BindingsError> {
    if let Some(parent) = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        fs::create_dir_all(parent).map_err(|source| BindingsError::Io {
            path: parent.to_path_buf(),
            source,
        })?;
    }
    fs::write(path, output).map_err(|source| BindingsError::Io {
        path: path.to_path_buf(),
        source,
    })
}

#[cfg(feature = "generate")]
fn check_generated(path: &Path, expected: String) -> Result<(), BindingsError> {
    let actual = fs::read_to_string(path).map_err(|source| BindingsError::Io {
        path: path.to_path_buf(),
        source,
    })?;
    if actual == expected {
        Ok(())
    } else {
        Err(BindingsError::Drift(path.to_path_buf()))
    }
}

#[derive(Debug)]
/// Failure while writing or checking deterministic generated bindings.
#[cfg(feature = "generate")]
pub enum BindingsError {
    /// Generated file or parent directory could not be accessed.
    Io {
        /// Path involved in the failed operation.
        path: PathBuf,
        /// Underlying filesystem error.
        source: std::io::Error,
    },
    /// Existing generated output differs from the current contract.
    Drift(PathBuf),
}

#[cfg(feature = "generate")]
impl fmt::Display for BindingsError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Io { path, source } => {
                write!(formatter, "cannot access {}: {source}", path.display())
            }
            Self::Drift(path) => write!(
                formatter,
                "generated bindings differ from {}; run `wabou bindings write`",
                path.display()
            ),
        }
    }
}

#[cfg(feature = "generate")]
impl std::error::Error for BindingsError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Io { source, .. } => Some(source),
            Self::Drift(_) => None,
        }
    }
}

#[cfg(feature = "generate")]
fn assert_identifier(value: &str, kind: &str) {
    assert!(
        is_contract_identifier(value),
        "invalid {kind} identifier `{value}`"
    );
}

#[cfg(feature = "generate")]
fn assert_native_widget_tag(tag: &str) {
    let mut characters = tag.chars();
    assert!(
        characters
            .next()
            .is_some_and(|character| character.is_ascii_lowercase())
            && characters.all(|character| {
                character.is_ascii_lowercase() || character.is_ascii_digit() || character == '-'
            }),
        "invalid native widget tag `{tag}`"
    );
}

#[cfg(feature = "generate")]
fn named_struct_fields(types: &Types, datatype: &DataType, component: &str) -> Vec<String> {
    fn collect(types: &Types, datatype: &DataType, component: &str, fields: &mut Vec<String>) {
        match datatype {
            DataType::Reference(Reference::Named(reference)) => {
                let datatype = types
                    .get(reference)
                    .and_then(|datatype| datatype.ty.as_ref())
                    .unwrap_or_else(|| panic!("widget `{component}` config type is unavailable"));
                collect(types, datatype, component, fields);
            }
            DataType::Struct(structure) => {
                let Fields::Named(named) = &structure.fields else {
                    panic!("widget `{component}` config must be a named-field struct");
                };
                fields.extend(
                    named
                        .fields
                        .iter()
                        .filter(|(_, field)| field.ty.is_some())
                        .map(|(name, _)| name.to_string()),
                );
            }
            DataType::Intersection(parts) => {
                for part in parts {
                    collect(types, part, component, fields);
                }
            }
            _ => panic!("widget `{component}` config must be a named-field struct"),
        }
    }

    let mut fields = Vec::new();
    collect(types, datatype, component, &mut fields);
    let mut unique = BTreeSet::new();
    for field in &fields {
        assert_identifier(field, "widget config field");
        assert!(
            unique.insert(field.clone()),
            "duplicate widget config field `{field}` in `{component}`"
        );
    }
    fields
}

/// Return whether `value` is a valid identifier for Wabou's generated
/// TypeScript capability and method contracts.
pub fn is_contract_identifier(value: &str) -> bool {
    let mut chars = value.chars();
    chars
        .next()
        .is_some_and(|character| character == '_' || character.is_ascii_alphabetic())
        && chars.all(|character| character == '_' || character.is_ascii_alphanumeric())
}

#[cfg(feature = "generate")]
fn render_mapped_datatype(
    types: &Types,
    datatype: &DataType,
) -> Result<String, specta_typescript::Error> {
    let exporter = Typescript::default();
    match datatype {
        DataType::Reference(reference) => primitives::reference(&exporter, types, reference),
        DataType::Nullable(inner) => {
            Ok(format!("{} | null", render_mapped_datatype(types, inner)?))
        }
        datatype => primitives::inline(&exporter, types, datatype),
    }
}

#[cfg(feature = "generate")]
fn specta_declarations(types: &Types, phase: specta_serde::Phase) -> BTreeMap<String, String> {
    let mapped = specta_serde::PhasesFormat
        .map_types(types)
        .unwrap_or_else(|error| panic!("cannot map Specta declarations: {error}"));
    let names = mapped
        .into_sorted_iter()
        .map(|datatype| datatype.name.to_string())
        .collect::<BTreeSet<_>>();
    let split_bases = names
        .iter()
        .filter_map(|name| name.strip_suffix("_Serialize"))
        .filter(|base| names.contains(*base) && names.contains(&format!("{base}_Deserialize")))
        .map(str::to_owned)
        .collect::<BTreeSet<_>>();
    let mut declarations = BTreeMap::new();
    for datatype in mapped
        .into_sorted_iter()
        .filter(|datatype| datatype.ty.is_some())
    {
        let name = datatype.name.as_ref();
        if split_bases.contains(name)
            || match phase {
                specta_serde::Phase::Serialize => name
                    .strip_suffix("_Deserialize")
                    .is_some_and(|base| split_bases.contains(base)),
                specta_serde::Phase::Deserialize => name
                    .strip_suffix("_Serialize")
                    .is_some_and(|base| split_bases.contains(base)),
            }
        {
            continue;
        }
        let declaration = primitives::export(
            &Typescript::default(),
            &mapped,
            std::iter::once(datatype),
            "",
        )
        .unwrap_or_else(|error| panic!("cannot export `{}`: {error}", datatype.name));
        let declaration = declaration
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
            .replacen("export type", "type", 1);
        merge_declaration(&mut declarations, datatype.name.to_string(), declaration);
    }
    declarations
}

#[cfg(test)]
#[cfg(feature = "generate")]
#[allow(dead_code)]
mod tests {
    use super::*;
    use serde::{Deserialize, Serialize};

    #[derive(Deserialize, Type)]
    #[serde(rename_all = "camelCase")]
    struct FunctionRequest {
        display_name: String,
    }

    #[derive(Serialize, Type)]
    struct FunctionResponse {
        accepted: bool,
    }

    #[derive(Deserialize, Type)]
    #[serde(rename_all = "camelCase")]
    struct PdfWidgetConfig {
        file_path: String,
        #[serde(default)]
        page: u32,
        #[serde(skip)]
        runtime_only: bool,
    }

    #[derive(Deserialize, Type)]
    struct SharedWidgetConfig {
        theme: String,
    }

    #[derive(Deserialize, Type)]
    struct FlattenedWidgetConfig {
        title: String,
        #[serde(flatten)]
        shared: SharedWidgetConfig,
    }

    #[test]
    fn contract_identifier_grammar_is_explicit_and_shared() {
        assert!(is_contract_identifier("workspace"));
        assert!(is_contract_identifier("_workspace2"));
        for invalid in ["", "1workspace", "work-space", "工作区"] {
            assert!(!is_contract_identifier(invalid), "accepted {invalid:?}");
        }
    }

    #[test]
    fn flat_function_modules_preserve_sync_and_async_signatures() {
        let output = FunctionModule::new("NativeFiles")
            .request_dto::<FunctionRequest>()
            .response_dto::<FunctionResponse>()
            .method(NativeMethod::asynchronous(
                "updateFile",
                &[("request", "FunctionRequest")],
                "FunctionResponse",
            ))
            .method(NativeMethod::sync("currentStatus", &[], "FunctionResponse"))
            .render();

        assert!(output.contains("displayName: string"));
        assert!(output.contains("accepted: boolean"));
        assert!(output.contains("updateFile(request: FunctionRequest): Promise<FunctionResponse>"));
        assert!(output.contains("currentStatus(): FunctionResponse"));
    }

    #[test]
    fn widget_modules_generate_reactive_solid_wrappers_from_serde_fields() {
        let output = WidgetModule::new()
            .widget::<PdfWidgetConfig>("PdfView", "pdf-view")
            .render();

        assert!(output.contains("filePath: string"));
        assert!(output.contains("page?: number"));
        assert!(!output.contains("runtimeOnly"));
        assert!(output.contains("tag=\"pdf-view\""));
        assert!(output.contains("config={config()}"));
    }

    #[test]
    fn widget_modules_split_flattened_serde_fields() {
        let output = WidgetModule::new()
            .widget::<FlattenedWidgetConfig>("Panel", "native-panel")
            .render();

        assert!(output.contains("title: props.title"));
        assert!(output.contains("theme: props.theme"));
        assert!(!output.contains("shared: props.shared"));
    }

    #[test]
    fn generated_file_checks_report_drift_without_rewriting() {
        let path = std::env::temp_dir().join(format!(
            "wabou-bindgen-{}-{}.ts",
            std::process::id(),
            line!()
        ));
        let module = FunctionModule::new("NativeFiles").method(NativeMethod::sync(
            "currentStatus",
            &[],
            "boolean",
        ));
        module.write(&path).unwrap();
        module.check(&path).unwrap();
        fs::write(&path, "stale").unwrap();
        assert!(matches!(module.check(&path), Err(BindingsError::Drift(_))));
        assert_eq!(fs::read_to_string(&path).unwrap(), "stale");
        fs::remove_file(path).unwrap();
    }
}
