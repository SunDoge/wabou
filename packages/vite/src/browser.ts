import { realpathSync } from "node:fs";
import { dirname, resolve } from "node:path";
import type { Plugin } from "vite";

/** Browser-specific host configuration; UI entries keep the normal mount API. */
export interface WabouBrowserOptions {
  /** Existing page canvas receiving Wabou paint. */
  canvas: string;
  /** wasm-bindgen's generated web JS module, relative to the application root. */
  runtimeModule: string;
  /** TTF/OTF URLs available to the shared Rust font context. */
  fonts?: readonly string[];
}
const BROWSER_ENTRY = "/@wabou/browser-entry.js";
const RESOLVED_BROWSER_ENTRY = "\0wabou-browser-entry";

/** @internal Host bootstrap generated by defineWabouConfig({ target: 'browser' }). */
export function browserHostPlugin(
  root: string,
  entry: string,
  options: WabouBrowserOptions,
): Plugin {
  const runtime = resolve(root, options.runtimeModule);
  const application = resolve(root, entry);
  return {
    name: "wabou-browser-host",
    enforce: "pre",
    config() {
      // Cargo wrappers can make target/ a symlink into a cache outside the workspace.
      const runtimeDirectory = dirname(realpathSync(runtime));
      return { server: { fs: { allow: [root, runtimeDirectory] } } };
    },
    resolveId(id) {
      return id === BROWSER_ENTRY ? RESOLVED_BROWSER_ENTRY : undefined;
    },
    load(id) {
      if (id !== RESOLVED_BROWSER_ENTRY) return;
      return [
        `import {startBrowserApp} from '@wabou/core/browser';`,
        `import init,{BrowserRuntime} from ${JSON.stringify(runtime)};`,
        `const canvas=document.querySelector(${JSON.stringify(options.canvas)});`,
        `if(!(canvas instanceof HTMLCanvasElement))throw new Error('Wabou browser host requires a canvas: '+${JSON.stringify(options.canvas)});`,
        `const dispose=await startBrowserApp({canvas,fonts:${JSON.stringify(options.fonts ?? [])},createRuntime:async canvas=>{await init();return new BrowserRuntime(canvas);},entry:()=>import(${JSON.stringify(application)})});`,
        `if(import.meta.hot){import.meta.hot.accept(${JSON.stringify(application)},()=>{});import.meta.hot.dispose(dispose);}`,
      ].join("\n");
    },
    transformIndexHtml: {
      order: "pre",
      handler() {
        return [
          {
            tag: "script",
            attrs: { type: "module", src: BROWSER_ENTRY },
            injectTo: "body",
          },
        ];
      },
    },
  };
}
